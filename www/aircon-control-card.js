class AirconControlCard extends HTMLElement {
  constructor() {
    super();
    this.attachShadow({ mode: "open" });

    this._config = null;
    this._hass = null;
    this._thermostatCard = null;
    this._thermostatBuildToken = 0;
    this._pendingSelections = new Map();
    this._selectionSequence = 0;
    this._controlsSignature = null;

    const stylesheet = document.createElement("link");
    stylesheet.rel = "stylesheet";
    stylesheet.href = CSS_URL;
    this.shadowRoot.append(stylesheet);

    this._root = document.createElement("div");
    this._root.className = "aircon-control";
    this.shadowRoot.append(this._root);
  }

  setConfig(config) {
    if (!config?.entity || typeof config.entity !== "string") {
      throw new Error("aircon-control-card requires an entity");
    }
    if (config.power_entity != null && typeof config.power_entity !== "string") {
      throw new Error("aircon-control-card power_entity must be a string");
    }
    if (config.fan_entity != null && typeof config.fan_entity !== "string") {
      throw new Error("aircon-control-card fan_entity must be a string");
    }

    this._clearPendingSelections();
    this._config = { ...config };
    this._controlsSignature = null;
    this._build();
  }

  set hass(hass) {
    this._hass = hass;

    if (this._thermostatCard) {
      this._thermostatCard.hass = hass;
    }

    this._ensureControlRows();
    this._updateSelection();
  }

  getCardSize() {
    return 8;
  }

  _build() {
    this._root.replaceChildren();
    this._thermostatCard = null;

    const thermostatHost = document.createElement("div");
    thermostatHost.className = "thermostat-host";
    this._root.append(thermostatHost);

    this._controlsHost = document.createElement("div");
    this._controlsHost.className = "controls-host";
    this._root.append(this._controlsHost);

    this._createThermostat(thermostatHost);
    this._ensureControlRows(true);
    this._updateSelection();
  }

  async _createThermostat(host) {
    const token = ++this._thermostatBuildToken;

    try {
      const helpers = await window.loadCardHelpers();
      const thermostat = await helpers.createCardElement({
        type: "thermostat",
        entity: this._config.entity,
      });

      if (token !== this._thermostatBuildToken) {
        return;
      }

      thermostat.hass = this._hass;
      this._thermostatCard = thermostat;
      host.replaceChildren(thermostat);
    } catch (error) {
      if (token !== this._thermostatBuildToken) {
        return;
      }

      const message = document.createElement("div");
      message.className = "error";
      message.textContent = `Unable to create thermostat card: ${error}`;
      host.replaceChildren(message);
    }
  }

  _getHvacGroup() {
    const stateObj = this._hass?.states?.[this._config?.entity];
    const supportedModes = Array.isArray(stateObj?.attributes?.hvac_modes)
      ? stateObj.attributes.hvac_modes
      : [];

    const supported = new Set(supportedModes);
    const buttons = [];

    for (const buttonDefinition of Object.values(HVAC_BUTTON_DEFINITIONS)) {
        if (supported.has(buttonDefinition.value)) {
          buttons.push(buttonDefinition);
        };
    };

    return {
      id: "hvac_mode",
      domain: "climate",
      service: "set_hvac_mode",
      entitySource: "climate",
      attribute: null,
      dataKey: "hvac_mode",
      buttons,
    };
  }

  _getVisibleGroups() {
    const groups = [];
    const hvacGroup = this._getHvacGroup();

    if (hvacGroup.buttons.length > 0) {
      groups.push(hvacGroup);
    }

    if (this._config?.fan_entity) {
      groups.push(FAN_PERCENTAGE_GROUP);
      groups.push(FAN_OSCILLATION_GROUP);
    } else {
      groups.push(CLIMATE_FAN_MODE_GROUP);
      groups.push(CLIMATE_VERTICAL_SWING_GROUP);
      groups.push(CLIMATE_HORIZONTAL_SWING_GROUP);
    }

    return groups;
  }

  _getControlsSignature(groups) {
    return JSON.stringify(
      groups.map((group) => ({
        id: group.id,
        buttons: group.buttons.map((button) => [button.value, button.name]),
      })),
    );
  }

  _ensureControlRows(force = false) {
    if (!this._controlsHost || !this._config) {
      return;
    }

    const groups = this._getVisibleGroups();
    const signature = this._getControlsSignature(groups);

    if (!force && signature === this._controlsSignature) {
      return;
    }

    this._controlsSignature = signature;
    this._controlsHost.replaceChildren(
      ...groups.map((group) => this._createSegmentedRow(group)),
    );
  }

  _createSegmentedRow(group) {
    const row = document.createElement("div");
    row.className = "segmented-row";
    
    if (group.id === "fan_mode" || group.id === "fan_percentage") {
        row.classList.add("fan-speed-row");
    }

    row.dataset.group = group.id;
    row.style.setProperty("--segment-count", group.buttons.length);

    group.buttons.forEach((definition, index) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "segment";
      button.dataset.value = this._valueKey(definition.value);
      button.dataset.group = group.id;
      button.setAttribute("aria-pressed", "false");

      if (index === 0) {
        button.classList.add("segment-left");
      } else if (index === group.buttons.length - 1) {
        button.classList.add("segment-right");
      } else {
        button.classList.add("segment-middle");
      }

      if (definition.icon) {
        const icon = document.createElement("ha-svg-icon");
        icon.className = "segment-icon";
        icon.path = SVG_ICON_PATHS[definition.icon];
        button.append(icon);
      } else {
        button.classList.add("no-icon");
      }

    //   const label = document.createElement("span");
    //   label.className = "segment-label";
    //   label.textContent = definition.name;
    //   button.append(label);

      button.addEventListener("click", () => {
        this._callControlService(group, definition);
      });

      row.append(button);
    });

    return row;
  }

  _callControlService(group, definition) {
    if (!this._hass || !this._config?.entity) {
      return;
    }

    const value = definition.value;
    const targetEntity = this._getControlEntity(group);
    if (!targetEntity) {
      return;
    }

    if (group.id === "hvac_mode" && this._config.power_entity) {
      const powerService = value === "off" ? "turn_off" : "turn_on";
      this._hass
        .callService("switch", powerService, {
          entity_id: this._config.power_entity,
        })
        .catch((error) => {
          console.error(
            `aircon-control-card: switch.${powerService} failed`,
            error,
          );
        });
    }

    const existing = this._pendingSelections.get(group.id);
    if (existing) {
      clearTimeout(existing.timerId);
    }

    const sequence = ++this._selectionSequence;
    const timerId = window.setTimeout(() => {
      const pending = this._pendingSelections.get(group.id);
      if (!pending || pending.sequence !== sequence) {
        return;
      }

      this._pendingSelections.delete(group.id);
      this._updateSelection();
    }, 10000);

    this._pendingSelections.set(group.id, {
      value,
      sequence,
      timerId,
    });

    this._updateSelection();

    const service = definition.service ?? group.service;
    const dataKey = definition.dataKey ?? group.dataKey;
    const serviceValue = Object.hasOwn(definition, "serviceValue")
      ? definition.serviceValue
      : value;

    this._hass
      .callService(group.domain, service, {
        entity_id: targetEntity,
        [dataKey]: serviceValue,
      })
      .catch((error) => {
        const pending = this._pendingSelections.get(group.id);
        if (!pending || pending.sequence !== sequence) {
          return;
        }

        clearTimeout(pending.timerId);
        this._pendingSelections.delete(group.id);
        this._updateSelection();
        console.error(
          `aircon-control-card: ${group.domain}.${service} failed`,
          error,
        );
      });
  }

  _getControlEntity(group) {
    if (group.entitySource === "fan") {
      return this._config?.fan_entity;
    }

    return this._config?.entity;
  }

  _getActualValue(group) {
    const entityId = this._getControlEntity(group);
    const stateObj = this._hass?.states?.[entityId];
    return group.attribute
      ? stateObj?.attributes?.[group.attribute]
      : stateObj?.state;
  }

  _valueKey(value) {
    return `${typeof value}:${String(value)}`;
  }

  _clearPendingSelections() {
    for (const pending of this._pendingSelections.values()) {
      clearTimeout(pending.timerId);
    }
    this._pendingSelections.clear();
  }

  disconnectedCallback() {
    this._clearPendingSelections();
  }

  _updateSelection() {
    if (!this._config || !this._hass || !this._controlsHost) {
      return;
    }

    const groups = this._getVisibleGroups();

    for (const group of groups) {
      const entityId = this._getControlEntity(group);
      const stateObj = this._hass.states[entityId];
      const available = Boolean(stateObj) && stateObj.state !== "unavailable";
      const actualValue = group.attribute
        ? stateObj?.attributes?.[group.attribute]
        : stateObj?.state;

      let selectedValue = actualValue;
      const pending = this._pendingSelections.get(group.id);

      if (pending) {
        if (available && actualValue === pending.value) {
          clearTimeout(pending.timerId);
          this._pendingSelections.delete(group.id);
        } else if (available) {
          selectedValue = pending.value;
        }
      }

      const buttons = this._controlsHost.querySelectorAll(
        `.segment[data-group="${group.id}"]`,
      );

      for (const button of buttons) {
        const selected =
          available && button.dataset.value === this._valueKey(selectedValue);
        button.classList.toggle("selected", selected);
        button.setAttribute("aria-pressed", selected ? "true" : "false");
        button.disabled = !available;
      }
    }
  }
}

